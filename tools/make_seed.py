"""Generate supabase/seed.sql from data/catalog-sakr.json + data/photos.json.

Run after the catalogue changes:  python tools/make_seed.py
Then load it in Supabase (SQL Editor, or `supabase db reset` with the CLI).
Re-running the seed is safe: it updates existing rows (upsert).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
catalog = json.loads((ROOT / 'data/catalog-sakr.json').read_text(encoding='utf8'))
photos = json.loads((ROOT / 'data/photos.json').read_text())

BRANDS = [('total', 'TOTAL', '#0b7480', 1), ('jadever', 'Jadever', '#1f7a37', 2)]
# TOTAL's 11 categories (same order and names as the website)
CATS = [
    ('power', 'Power Tools', 'Outillage électrique', 'عدّة كهربائية'),
    ('accessories', 'Power Tools Accessories', 'Accessoires d’outillage', 'ملحقات العدّة الكهربائية'),
    ('generators', 'Generators', 'Groupes électrogènes', 'مولّدات'),
    ('welding', 'Welding Machines', 'Postes à souder', 'ماكينات لحام'),
    ('construction', 'Small Construction Equipment', 'Petit matériel de chantier', 'معدّات بناء صغيرة'),
    ('air', 'Air Tools', 'Outils pneumatiques', 'عدّة هوائية'),
    ('pumps', 'Water Pumps', 'Pompes à eau', 'مضخات مياه'),
    ('hand', 'Hand Tools', 'Outils à main', 'أدوات يدوية'),
    ('measure', 'Measuring Tools', 'Outils de mesure', 'أدوات قياس'),
    ('safety', 'Safety Products', 'Équipements de sécurité', 'معدّات سلامة'),
    ('garden', 'Garden Tools', 'Outils de jardin', 'أدوات حديقة'),
]


def lit(v):
    if v is None:
        return 'null'
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


out = ['-- Generated by tools/make_seed.py. Do not edit by hand.',
       '-- Prices are SAKR reference prices used as PLACEHOLDERS until DAR sends its price list.', '']
out.append('insert into public.brands (id, name, color, sort) values')
out.append(',\n'.join(f'  ({lit(i)}, {lit(n)}, {lit(c)}, {s})' for i, n, c, s in BRANDS))
out.append('on conflict (id) do update set name = excluded.name, color = excluded.color, sort = excluded.sort;\n')
out.append('insert into public.categories (id, sort, name_en, name_fr, name_ar) values')
out.append(',\n'.join(f'  ({lit(i)}, {k}, {lit(en)}, {lit(fr)}, {lit(ar)})' for k, (i, en, fr, ar) in enumerate(CATS)))
out.append('on conflict (id) do update set sort = excluded.sort, name_en = excluded.name_en, name_fr = excluded.name_fr, name_ar = excluded.name_ar;\n')
out.append('insert into public.products (id, brand_id, category_id, code, name, price_usd, price_max_usd, image_url, popularity, source_url) values')
rows = []
for rank, p in enumerate(catalog):
    rows.append(f"  ({lit(p['id'])}, {lit(p['brand'])}, {lit(p['cat'])}, {lit(p['code'] or None)}, {lit(p['name'])}, "
                f"{p['refPrice']}, {lit(p['refPriceMax'])}, {lit(photos.get(p['id']))}, {rank}, {lit(p['source'])})")
out.append(',\n'.join(rows))
out.append('on conflict (id) do update set brand_id = excluded.brand_id, category_id = excluded.category_id, code = excluded.code,\n'
           '  name = excluded.name, price_usd = excluded.price_usd, price_max_usd = excluded.price_max_usd,\n'
           '  image_url = excluded.image_url, popularity = excluded.popularity, source_url = excluded.source_url;')
(ROOT / 'supabase').mkdir(exist_ok=True)
(ROOT / 'supabase/seed.sql').write_text('\n'.join(out) + '\n', encoding='utf8')
print(f'seed.sql: {len(BRANDS)} brands, {len(CATS)} categories, {len(rows)} products')
